def _reduce_number(n: int, keep_master: bool = False) -> int:
    """Свести число к однозначному (опционально сохраняя мастер-числа 11, 22, 33)."""
    if keep_master:
        while n > 9 and n not in (11, 22, 33):
            n = sum(int(d) for d in str(n))
    else:
        while n > 9:
            n = sum(int(d) for d in str(n))
    return n


def _numerology_core(day: int, month: int, year: int) -> int:
    """Рассчитать число жизненного пути."""
    total = sum(int(d) for d in f"{day}{month}{year}")
    return _reduce_number(total, keep_master=True)


