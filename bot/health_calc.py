# ────────────────────────────────────────────────────────────────
#  4. Циркадные рекомендации
# ────────────────────────────────────────────────────────────────

def calculate_circadian_recommendations(dosha_type: str, wake_time: str) -> Dict[str, Any]:
    """Рассчитать циркадные рекомендации на основе доши и времени пробуждения.

    dosha_type: "vata" | "pitta" | "kapha"
    wake_time: строка "HH:MM"
    Возвращает: расписание дня с оптимальным временем для еды, работы, отдыха.
    """
    dosha = dosha_type.lower().strip()
    if dosha not in CIRCADIAN_SCHEDULES:
        dosha = "vata"

    schedule_data = CIRCADIAN_SCHEDULES[dosha]
    ideal_wake = schedule_data["wake_ideal"]

    # Парсим время пробуждения
    try:
        parts = wake_time.replace(".", ":").split(":")
        wake_h = int(parts[0])
        wake_m = int(parts[1]) if len(parts) > 1 else 0
    except (ValueError, IndexError):
        wake_h, wake_m = 6, 0

    # Определяем качество времени пробуждения
    wake_quality = ""
    dosha_times = {
        "vata": {"ideal": (5, 30, 6, 0), "late": (7, 0, 10, 0)},
        "pitta": {"ideal": (5, 30, 6, 0), "late": (7, 0, 10, 0)},
        "kapha": {"ideal": (4, 30, 5, 30), "late": (6, 0, 8, 0)},
    }

    dt = dosha_times[dosha]
    wake_minutes = wake_h * 60 + wake_m
    ideal_start = dt["ideal"][0] * 60 + dt["ideal"][1]
    ideal_end = dt["ideal"][2] * 60 + dt["ideal"][3]
    late_start = dt["late"][0] * 60 + dt["late"][1]
    late_end = dt["late"][2] * 60 + dt["late"][3]

    if ideal_start <= wake_minutes <= ideal_end:
        wake_quality = "идеальное время пробуждения"
    elif late_start <= wake_minutes <= late_end:
        wake_quality = "поздновато, но допустимо"
    elif wake_minutes > late_end:
        wake_quality = "слишком поздно — доша выходит из равновесия"
    else:
        wake_quality = "очень рано, отлично для духовных практик"

    # Корректируем расписание под время пробуждения
    offset_minutes = wake_minutes - (5 * 60 + 30 if dosha != "kapha" else 5 * 60)

    adjusted_schedule = []
    for item in schedule_data["schedule"]:
        try:
            time_parts = item["time"].split(":")
            item_h = int(time_parts[0])
            item_m = int(time_parts[1]) if len(time_parts) > 1 else 0
            adjusted_h = item_h + offset_minutes // 60
            adjusted_m = item_m + offset_minutes % 60
            if adjusted_m >= 60:
                adjusted_h += 1
                adjusted_m -= 60
            adjusted_time = f"{adjusted_h:02d}:{adjusted_m:02d}"
        except (ValueError, IndexError):
            adjusted_time = item["time"]

        adjusted_schedule.append({
            "original_time": item["time"],
            "adjusted_time": adjusted_time,
            "activity": item["activity"],
            "detail": item["detail"],
        })

    # Аюрведические часы (активность дош по времени суток)
    dosha_clock = [
        {"period": "02:00–06:00", "active_dosha": "Вата", "recommendation": "Время пробуждения и духовных практик. Не спите после 6:00!"},
        {"period": "06:00–10:00", "active_dosha": "Капха", "recommendation": "Время лёгкой активности. Не завтракайте тяжело, двигайтесь."},
        {"period": "10:00–14:00", "active_dosha": "Питта", "recommendation": "Пик пищеварения — основной приём пищи в 12:00. Максимальная продуктивность."},
        {"period": "14:00–18:00", "active_dosha": "Вата", "recommendation": "Творчество, коммуникация. Перекус в 15:00–16:00. Не переутомляйтесь."},
        {"period": "18:00–22:00", "active_dosha": "Капха", "recommendation": "Замедление, лёгкий ужин до 19:30. Успокаивающие практики."},
        {"period": "22:00–02:00", "active_dosha": "Питта", "recommendation": "Глубокий сон. Печень активна — детокс. Не ешьте и не бодрствуйте!"},
    ]

    return {
        "dosha": dosha,
        "wake_time": wake_time,
        "ideal_wake_time": ideal_wake,
        "wake_quality": wake_quality,
        "schedule_description": schedule_data["description"],
        "original_schedule": schedule_data["schedule"],
        "adjusted_schedule": adjusted_schedule,
        "dosha_clock": dosha_clock,
        "analysis": (
            f"Циркадные рекомендации для {schedule_data['dosha']}-конституции. "
            f"Ваше время пробуждения: {wake_time} ({wake_quality}). "
            f"Идеальное время: {ideal_wake}. {schedule_data['description']}"
        ),
    }


# ────────────────────────────────────────────────────────────────
#  5. Чакры: анализ баланса
# ────────────────────────────────────────────────────────────────

def calculate_chakra_analysis(day: int, month: int, year: int) -> Dict[str, Any]:
    """Рассчитать баланс чакр на основе нумерологии даты рождения.

    Каждая чакра получает оценку 1-10 на основе нумерологических расчётов.
    Возвращает: сбалансированные/несбалансированные чакры с рекомендациями.
    """
    # Нумерологические базовые числа
    life_path = _numerology_core(day, month, year)
    day_reduced = _reduce_number(day, keep_master=False)
    month_reduced = _reduce_number(month, keep_master=False)
    year_reduced = _reduce_number(sum(int(d) for d in str(year)), keep_master=False)
    full_sum = _reduce_number(day + month + sum(int(d) for d in str(year)), keep_master=False)

    # Расчёт баланса каждой чакры (1-10)
    # Метод: комбинация нумерологических влияний на каждую чакру
    chakra_scores: Dict[str, float] = {}

    # Муладхара (1) — основа, выживание, земля
    chakra_scores["muladhara"] = (
        5.0
        + (1 if day_reduced in (1, 4, 8) else 0)
        + (1 if life_path in (1, 4, 8) else 0)
        + (1 if year_reduced in (1, 4) else 0)
        + (0.5 if month_reduced == 1 else 0)
        + (0.5 if full_sum in (1, 4) else 0)
    )

    # Свадхистхана (2) — эмоции, вода, творчество
    chakra_scores["svadhisthana"] = (
        5.0
        + (1 if day_reduced in (2, 7, 9) else 0)
        + (1 if life_path in (2, 7, 9) else 0)
        + (1 if month_reduced == 2 else 0)
        + (0.5 if year_reduced == 2 else 0)
        + (0.5 if full_sum == 2 else 0)
    )

    # Манипура (3) — воля, огонь, сила
    chakra_scores["manipura"] = (
        5.0
        + (1 if day_reduced in (3, 5) else 0)
        + (1 if life_path in (3, 5) else 0)
        + (1 if month_reduced == 3 else 0)
        + (0.5 if year_reduced == 3 else 0)
        + (0.5 if full_sum == 5 else 0)
    )

    # Анахата (4) — любовь, воздух, связь
    chakra_scores["anahata"] = (
        5.0
        + (1 if day_reduced in (2, 6, 9) else 0)
        + (1 if life_path in (2, 6, 9) else 0)
        + (1 if month_reduced == 6 else 0)
        + (0.5 if year_reduced == 6 else 0)
        + (0.5 if full_sum == 6 else 0)
    )

    # Вишуддха (5) — выражение, эфир, истина
    chakra_scores["vishuddha"] = (
        5.0
        + (1 if day_reduced in (3, 5) else 0)
        + (1 if life_path in (3, 5) else 0)
        + (1 if month_reduced == 5 else 0)
        + (0.5 if year_reduced == 5 else 0)
        + (0.5 if full_sum == 3 else 0)
    )

    # Аджна (6) — интуиция, свет, знание
    chakra_scores["ajna"] = (
        5.0
        + (1.5 if life_path in (7, 11) else 0)
        + (1 if day_reduced == 7 else 0)
        + (1 if month_reduced == 7 else 0)
        + (0.5 if year_reduced == 7 else 0)
        + (0.5 if full_sum == 7 else 0)
    )

    # Сахасрара (7) — дух, космос, единство
    chakra_scores["sahasrara"] = (
        5.0
        + (1.5 if life_path in (9, 11, 22, 33) else 0)
        + (1 if day_reduced == 9 else 0)
        + (1 if month_reduced == 9 else 0)
        + (0.5 if year_reduced == 9 else 0)
        + (0.5 if full_sum == 9 else 0)
    )

    # Ограничиваем 1-10
    for key in chakra_scores:
        chakra_scores[key] = max(1.0, min(10.0, round(chakra_scores[key], 1)))

    # Классификация
    balanced = []
    imbalanced_low = []
    imbalanced_high = []

    for chakra_key, score in chakra_scores.items():
        chakra_info = CHAKRA_DESCRIPTIONS.get(chakra_key, {})
        entry = {
            "key": chakra_key,
            "name": chakra_info.get("name", chakra_key),
            "score": score,
            "color": chakra_info.get("color", ""),
            "mantra": chakra_info.get("mantra", ""),
            "crystal": chakra_info.get("crystal", ""),
        }
        if score >= 7.0:
            balanced.append(entry)
        elif score <= 4.0:
            imbalanced_low.append(entry)
        else:
            balanced.append(entry)  # средний уровень тоже считаем нормой

    # Находим самую слабую чакру для приоритетной работы
    weakest_key = min(chakra_scores, key=chakra_scores.get)  # type: ignore[arg-type]
    weakest_info = CHAKRA_DESCRIPTIONS.get(weakest_key, {})

    # Находим самую сильную
    strongest_key = max(chakra_scores, key=chakra_scores.get)  # type: ignore[arg-type]
    strongest_info = CHAKRA_DESCRIPTIONS.get(strongest_key, {})

    return {
        "scores": chakra_scores,
        "balanced": balanced,
        "imbalanced_low": imbalanced_low,
        "weakest_chakra": {
            "key": weakest_key,
            "info": weakest_info,
            "score": chakra_scores[weakest_key],
        },
        "strongest_chakra": {
            "key": strongest_key,
            "info": strongest_info,
            "score": chakra_scores[strongest_key],
        },
        "life_path_number": life_path,
        "analysis": (
            f"Анализ чакр по дате рождения ({day}.{month}.{year}). "
            f"Число жизненного пути: {life_path}. "
            f"Сильнейшая чакра: {strongest_info.get('name', strongest_key)} "
            f"({chakra_scores[strongest_key]}/10) — ваш природный дар. "
            f"Слабейшая чакра: {weakest_info.get('name', weakest_key)} "
            f"({chakra_scores[weakest_key]}/10) — зона роста и исцеления. "
            f"Для гармонизации работайте с {weakest_info.get('name', weakest_key)}: "
            f"визуализируйте {weakest_info.get('color', '')} цвет, "
            f"пойте мантру {weakest_info.get('mantra', '')}, "
            f"носите {weakest_info.get('crystal', '').split(',')[0].strip()}."
        ),
    }


