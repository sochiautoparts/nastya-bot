PYTHAGOREAN_MAP = {
    'a': 1, 'b': 2, 'c': 3, 'd': 4, 'e': 5, 'f': 6,
    'g': 7, 'h': 8, 'i': 9, 'j': 1, 'k': 2, 'l': 3,
    'm': 4, 'n': 5, 'o': 6, 'p': 7, 'q': 8, 'r': 9,
    's': 1, 't': 2, 'u': 3, 'v': 4, 'w': 5, 'x': 6,
    'y': 7, 'z': 8,
}

VOWELS = set('aeiou')
CONSONANTS = set('bcdfghjklmnpqrstvwxyz')


def _reduce(n: int, keep_master: bool = True) -> int:
    """Редуцирует число к одной цифре, сохраняя мастер-числа (11, 22, 33)."""
    if n < 1:
        return n
    if keep_master and n in (11, 22, 33):
        return n
    while n > 9:
        if keep_master and n in (11, 22, 33):
            return n
        s = 0
        temp = n
        while temp:
            s += temp % 10
            temp //= 10
        n = s
    return n


def _reduce_full(n: int) -> int:
    """Полное редуцирование без сохранения мастер-чисел."""
    while n > 9:
        s = 0
        temp = n
        while temp:
            s += temp % 10
            temp //= 10
        n = s
    return n


def _letter_value(ch: str) -> int:
    """Возвращает числовое значение буквы по Пифагорейской системе."""
    return PYTHAGOREAN_MAP.get(ch.lower(), 0)


def _name_to_numbers(name_translit: str) -> List[int]:
    """Преобразует транслитерированное имя в список чисел."""
    return [_letter_value(ch) for ch in name_translit if ch.lower() in PYTHAGOREAN_MAP]


def _vowel_sum(name_translit: str) -> int:
    """Сумма гласных (Число Души / Soul Urge)."""
    return sum(_letter_value(ch) for ch in name_translit
               if ch.lower() in VOWELS and ch.lower() in PYTHAGOREAN_MAP)


def _consonant_sum(name_translit: str) -> int:
    """Сумма согласных (Число Личности / Personality)."""
    return sum(_letter_value(ch) for ch in name_translit
               if ch.lower() in CONSONANTS and ch.lower() in PYTHAGOREAN_MAP)


def _full_name_sum(name_translit: str) -> int:
    """Сумма всех букв (Число Судьбы / Destiny / Expression)."""
    return sum(_letter_value(ch) for ch in name_translit
               if ch.lower() in PYTHAGOREAN_MAP)


def _first_letters_sum(name_translit: str) -> int:
    """Сумма первых букв каждого слова в полном имени."""
    words = name_translit.strip().split()
    return sum(_letter_value(w[0]) for w in words if w)


