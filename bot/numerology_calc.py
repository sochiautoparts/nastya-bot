    # --- Число зрелости ---
    result["maturity_number"] = calculate_maturity_number(
        day, month, year, full_name_translit
    )

    # --- Число баланса ---
    if full_name_translit:
        result["balance_number"] = calculate_balance_number(full_name_translit)

    # --- Рациональное мышление ---
    result["rational_thought"] = calculate_rational_thought(day)

    # --- Подсознательное «Я» ---
    if full_name_translit:
        result["subconscious_self"] = calculate_subconscious_self(full_name_translit)

    # --- Скрытая страсть ---
    if full_name_translit:
        result["hidden_passion"] = calculate_hidden_passion(full_name_translit)

    # --- Кармические уроки ---
    if full_name_translit:
        result["karmic_lessons"] = calculate_karmic_lessons(full_name_translit)

    # --- Кармические долги ---
    result["karmic_debts"] = calculate_karmic_debts(day, month, year)

    # --- Вершины ---
    result["pinnacle_numbers"] = calculate_pinnacle_numbers(day, month, year)

    # --- Вызовы ---
    result["challenge_numbers"] = calculate_challenge_numbers(day, month, year)

    # --- Периодические циклы ---
    result["period_cycles"] = calculate_period_cycles(day, month, year)

    # --- Новые профессиональные расчёты ---
    # Вычисляем текущий возраст для транзитных расчётов
    from datetime import date as _date
    today = _date.today()
    try:
        last_birthday = _date(today.year, month, day)
        current_age = today.year - year - (1 if today < last_birthday else 0)
    except ValueError:
        # 29 февраля в невысокосный год
        current_age = today.year - year

    if full_name_translit:
        # --- Транзитные буквы ---
        result["transit_letters"] = calculate_transit_letters(
            full_name_translit, current_age
        )

        # --- Число Сущности ---
        result["essence_number"] = calculate_essence_number(
            full_name_translit, current_age
        )

        # --- Краеугольный и Завершающий Камни ---
        result["cornerstone_capstone"] = calculate_cornerstone_capstone(
            full_name_translit
        )

        # --- Подсознательное «Я» (по имени, формула 9 - missing) ---
        result["subconscious_self_name"] = calculate_subconscious_self_name(
            full_name_translit
        )

        # --- Рациональное мышление (по имени) ---
        result["rational_thought_name"] = calculate_rational_thought_name(
            full_name_translit
        )

    return result


