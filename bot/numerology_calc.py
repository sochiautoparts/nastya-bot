def calculate_transit_letters(name_translit: str, current_age: int) -> Dict:
    """
    Вычисляет текущие транзитные буквы для каждой части имени.

    Каждая буква имеет длительность транзита, равную её Пифагорейскому значению.
    Буквы «проходятся» последовательно, и по достижении конца имени цикл
    начинается заново.

    Параметры:
        name_translit: полное имя в транслитерации (например, "Ivan Petrov Sidorov")
        current_age: текущий возраст человека

    Возвращает:
        Словарь с текущими транзитными буквами для каждого слова имени,
        их числовыми значениями и интерпретациями.
    """
    words = name_translit.strip().split()
    if not words:
        return {
            "transits": [],
            "current_age": current_age,
        }

    transits = []
    for word_idx, word in enumerate(words):
        letters = [ch for ch in word.lower() if ch in PYTHAGOREAN_MAP]
        if not letters:
            continue

        # Длительность полного цикла этого слова = сумма значений всех букв
        cycle_length = sum(PYTHAGOREAN_MAP[ch] for ch in letters)
        if cycle_length == 0:
            continue

        # Позиция в цикле для текущего возраста
        age_in_cycle = current_age % cycle_length

        # Идём по буквам, суммируя их длительности, пока не дойдём до текущего возраста
        accumulated = 0
        current_letter_idx = 0
        for i, ch in enumerate(letters):
            letter_duration = PYTHAGOREAN_MAP[ch]
            if accumulated + letter_duration > age_in_cycle:
                current_letter_idx = i
                break
            accumulated += letter_duration
            if i == len(letters) - 1:
                current_letter_idx = i

        current_letter = letters[current_letter_idx]
        current_value = PYTHAGOREAN_MAP[current_letter]
        years_remaining = (accumulated + PYTHAGOREAN_MAP[letters[current_letter_idx]]) - age_in_cycle

        word_label = ""
        if len(words) == 3:
            word_label = ["Имя", "Отчество", "Фамилия"][word_idx] if word_idx < 3 else f"Слово {word_idx + 1}"
        elif len(words) == 2:
            word_label = ["Имя", "Фамилия"][word_idx] if word_idx < 2 else f"Слово {word_idx + 1}"
        else:
            word_label = f"Слово {word_idx + 1}"

        transits.append({
            "word": word,
            "word_label": word_label,
            "current_letter": current_letter.upper(),
            "current_value": current_value,
            "years_remaining_in_transit": years_remaining,
            "meaning": TRANSIT_LETTER_MEANINGS.get(
                current_value, "Интерпретация недоступна."
            ),
        })

    return {
        "transits": transits,
        "current_age": current_age,
    }


def calculate_essence_number(name_translit: str, current_age: int) -> Dict:
    """
    Вычисляет Число Сущности (Essence Number) для текущего возраста.

    Число Сущности = сумма текущих транзитных значений всех слов имени,
    редуцированная до одной цифры (с сохранением мастер-чисел).

    Параметры:
        name_translit: полное имя в транслитерации
        current_age: текущий возраст человека

    Возвращает:
        Словарь с числом сущности, транзитными значениями и интерпретацией.
    """
    transit_data = calculate_transit_letters(name_translit, current_age)
    transit_values = [t["current_value"] for t in transit_data.get("transits", [])]

    if not transit_values:
        return {
            "number": 0,
            "transit_values": [],
            "transit_letters": [],
            "meaning": "Недостаточно данных для расчёта.",
        }

    essence_raw = sum(transit_values)
    essence = _reduce(essence_raw, keep_master=True)

    return {
        "number": essence,
        "raw_sum": essence_raw,
        "transit_values": transit_values,
        "transit_letters": [t["current_letter"] for t in transit_data.get("transits", [])],
        "meaning": ESSENCE_MEANINGS.get(essence, "Интерпретация недоступна."),
    }


def calculate_cornerstone_capstone(name_translit: str) -> Dict:
    """
    Вычисляет Краеугольный Камень (Cornerstone) и Завершающий Камень (Capstone).

    Cornerstone — первая буква первого слова имени → показывает, как человек
    подходит к жизни и начинает дела.
    Capstone — последняя буква последнего слова имени → показывает, как
    человек завершает дела и заканчивает этапы жизни.

    Параметры:
        name_translit: полное имя в транслитерации

    Возвращает:
        Словарь с Cornerstone и Capstone значениями и интерпретациями.
    """
    words = name_translit.strip().split()
    if not words:
        return {
            "cornerstone": {"letter": "", "value": 0, "meaning": ""},
            "capstone": {"letter": "", "value": 0, "meaning": ""},
        }

    # Cornerstone: первая буква первого слова
    first_word = words[0]
    cornerstone_letter = ""
    for ch in first_word:
        if ch.lower() in PYTHAGOREAN_MAP:
            cornerstone_letter = ch
            break
    cornerstone_value = _letter_value(cornerstone_letter) if cornerstone_letter else 0

    # Capstone: последняя буква последнего слова
    last_word = words[-1]
    capstone_letter = ""
    for ch in reversed(last_word):
        if ch.lower() in PYTHAGOREAN_MAP:
            capstone_letter = ch
            break
    capstone_value = _letter_value(capstone_letter) if capstone_letter else 0

    return {
        "cornerstone": {
            "letter": cornerstone_letter.upper(),
            "value": cornerstone_value,
            "meaning": CORNERSTONE_MEANINGS.get(
                cornerstone_value, "Интерпретация недоступна."
            ),
        },
        "capstone": {
            "letter": capstone_letter.upper(),
            "value": capstone_value,
            "meaning": CAPSTONE_MEANINGS.get(
                capstone_value, "Интерпретация недоступна."
            ),
        },
    }


def calculate_subconscious_self_name(name_translit: str) -> Dict:
    """
    Вычисляет Число Подсознательного «Я» (Subconscious Self) по имени.

    Формула: Подсознательное Я = 9 минус количество отсутствующих
    чисел (1-9) в Пифагорейской карте имени.

    Чем больше разных чисел присутствует в имени, тем выше число
    Подсознательного «Я» и тем более универсальным и адаптивным
    является внутренний мир человека.

    Параметры:
        name_translit: полное имя в транслитерации

    Возвращает:
        Словарь с числом, списками присутствующих/отсутствующих чисел
        и интерпретацией.
    """
    numbers = _name_to_numbers(name_translit)
    from collections import Counter
    freq = Counter(numbers)

    present = set(freq.keys()) & set(range(1, 10))
    all_digits = set(range(1, 10))
    missing = sorted(all_digits - present)

    # Подсознательное Я = 9 минус количество отсутствующих чисел
    subconscious = 9 - len(missing)

    return {
        "number": subconscious,
        "present_numbers": sorted(present),
        "missing_numbers": missing,
        "present_count": len(present),
        "missing_count": len(missing),
        "meaning": SUBCONSCIOUS_SELF_MEANINGS.get(
            subconscious, "Интерпретация недоступна."
        ),
    }


def calculate_rational_thought_name(name_translit: str) -> Dict:
    """
    Вычисляет Число Рационального Мышления (Rational Thought Number) по имени.

    Формула: сумма гласных первого слова + значение первой буквы первого слова,
    результат редуцируется до одной цифры (с сохранением мастер-чисел).

    Показывает, как человек обрабатывает информацию и принимает решения,
    учитывая как интеллектуальную (гласные), так и инициирующую (первая буква)
    составляющие мышления.

    Параметры:
        name_translit: полное имя в транслитерации

    Возвращает:
        Словарь с числом рационального мышления и интерпретацией.
    """
    words = name_translit.strip().split()
    if not words:
        return {
            "number": 0,
            "first_word": "",
            "vowel_sum": 0,
            "first_letter_value": 0,
            "meaning": "Недостаточно данных для расчёта.",
        }

    first_word = words[0]

    # Сумма гласных первого слова
    vowel_sum_first = sum(
        _letter_value(ch) for ch in first_word
        if ch.lower() in VOWELS and ch.lower() in PYTHAGOREAN_MAP
    )

    # Значение первой буквы первого слова
    first_letter_value = _letter_value(first_word[0]) if first_word else 0

    # Сумма и редукция
    raw_sum = vowel_sum_first + first_letter_value
    number = _reduce(raw_sum, keep_master=True)

    return {
        "number": number,
        "first_word": first_word,
        "vowel_sum": vowel_sum_first,
        "first_letter_value": first_letter_value,
        "raw_sum": raw_sum,
        "meaning": RATIONAL_THOUGHT_MEANINGS.get(
            number, "Интерпретация недоступна."
        ),
    }


