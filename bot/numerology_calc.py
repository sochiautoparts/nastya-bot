def calculate_karmic_debts(day: int, month: int, year: int) -> Dict:
    """
    Обнаруживает кармические долги (13, 14, 16, 19) в дате рождения.

    Проверяет:
    - день (как есть)
    - месяц (как есть)
    - год (редуцированный)
    - сумму день+месяц+год до редукции (жизненный путь до редукции)

    Возвращает словарь с найденными долгами и их описаниями.
    """
    debts_found: Dict[int, str] = {}

    # Проверяем день
    if day in KARMIC_DEBT_MEANINGS:
        debts_found[day] = KARMIC_DEBT_MEANINGS[day]

    # Проверяем месяц
    if month in KARMIC_DEBT_MEANINGS:
        debts_found[month] = KARMIC_DEBT_MEANINGS[month]

    # Проверяем редуцированный год
    reduced_year = _reduce(year, keep_master=False)
    if reduced_year in KARMIC_DEBT_MEANINGS:
        debts_found[reduced_year] = KARMIC_DEBT_MEANINGS[reduced_year]

    # Проверяем промежуточные суммы при редукции дня
    temp_day = day
    while temp_day > 9:
        temp_day_sum = 0
        d = temp_day
        while d:
            temp_day_sum += d % 10
            d //= 10
        if temp_day_sum in KARMIC_DEBT_MEANINGS and temp_day_sum not in debts_found:
            debts_found[temp_day_sum] = KARMIC_DEBT_MEANINGS[temp_day_sum]
        temp_day = temp_day_sum

    # Проверяем промежуточные суммы при редукции месяца
    temp_month = month
    while temp_month > 9:
        temp_month_sum = 0
        m = temp_month
        while m:
            temp_month_sum += m % 10
            m //= 10
        if temp_month_sum in KARMIC_DEBT_MEANINGS and temp_month_sum not in debts_found:
            debts_found[temp_month_sum] = KARMIC_DEBT_MEANINGS[temp_month_sum]
        temp_month = temp_month_sum

    # Проверяем промежуточные суммы при редукции года
    temp_year = year
    while temp_year > 9:
        temp_year_sum = 0
        y = temp_year
        while y:
            temp_year_sum += y % 10
            y //= 10
        if temp_year_sum in KARMIC_DEBT_MEANINGS and temp_year_sum not in debts_found:
            debts_found[temp_year_sum] = KARMIC_DEBT_MEANINGS[temp_year_sum]
        temp_year = temp_year_sum

    # Проверяем сумму дня, месяца и года до финальной редукции (Life Path)
    lp_raw = _reduce_full(day) + _reduce_full(month) + _reduce_full(year)
    if lp_raw in KARMIC_DEBT_MEANINGS and lp_raw not in debts_found:
        debts_found[lp_raw] = KARMIC_DEBT_MEANINGS[lp_raw]

    return {
        "karmic_debts": list(debts_found.keys()),
        "descriptions": debts_found,
        "has_karmic_debt": len(debts_found) > 0,
    }


def calculate_pinnacle_numbers(day: int, month: int, year: int) -> Dict:
    """
    Вычисляет 4 числа Вершины (Pinnacles) и их возрастные диапазоны.

    - 1-я Вершина: месяц + день (от 0 до 36 − LifePath)
    - 2-я Вершина: день + год (следующие 9 лет)
    - 3-я Вершина: Вершина1 + Вершина2 (следующие 9 лет)
    - 4-я Вершина: месяц + год (остальная жизнь)
    """
    life_path = _reduce_full(calculate_life_path(day, month, year))

    # Редуцируем компоненты (без сохранения мастер-чисел для вычисления вершин)
    r_month = _reduce(month, keep_master=False)
    r_day = _reduce(day, keep_master=False)
    r_year = _reduce(year, keep_master=False)

    p1 = _reduce(r_month + r_day, keep_master=True)
    p2 = _reduce(r_day + r_year, keep_master=True)
    p3 = _reduce(_reduce(p1, keep_master=False) + _reduce(p2, keep_master=False), keep_master=True)
