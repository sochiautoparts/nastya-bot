def calculate_hidden_passion(full_name_translit: str) -> Dict:
    """
    Вычисляет Скрытую Страсть (Hidden Passion).
    Число, которое чаще всего встречается в имени.
    """
    numbers = _name_to_numbers(full_name_translit)
    if not numbers:
        return {
            "number": None,
            "frequency": 0,
            "meaning": "Имя не содержит распознаваемых букв.",
        }

    from collections import Counter
    freq = Counter(numbers)
    max_freq = max(freq.values())
    most_frequent = [n for n, c in freq.items() if c == max_freq]

    # Если несколько чисел с одинаковой частотой — берём все
    results = []
    for num in most_frequent:
        results.append({
            "number": num,
            "frequency": max_freq,
            "meaning": HIDDEN_PASSION_MEANINGS.get(num, "Интерпретация недоступна."),
        })

    return {
        "hidden_passions": results,
        "frequency_distribution": dict(sorted(freq.items())),
    }


def calculate_karmic_lessons(full_name_translit: str) -> Dict:
    """
    Вычисляет Кармические Уроки (Karmic Lessons).
    Числа от 1 до 9, которые ОТСУТСТВУЮТ в имени (0 вхождений).
    """
    numbers = _name_to_numbers(full_name_translit)
    from collections import Counter
    freq = Counter(numbers)

    present = set(freq.keys())
    all_digits = set(range(1, 10))
    missing = sorted(all_digits - present)

    lessons = []
    for num in missing:
        lessons.append({
            "number": num,
            "meaning": KARMIC_LESSON_MEANINGS.get(num, "Интерпретация недоступна."),
        })

    return {
        "karmic_lessons": lessons,
        "missing_numbers": missing,
        "has_karmic_lessons": len(missing) > 0,
        "frequency_distribution": dict(sorted(freq.items())),
    }


