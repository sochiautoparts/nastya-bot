def format_numerology_report(day: int, month: int, year: int,
                             full_name_translit: str = "") -> str:
    """
    Форматирует полный нумерологический отчёт в текст для Telegram.
    Разбивает на части для удобства чтения.
    """
    data = calculate_all_numerology(day, month, year, full_name_translit)

    lines: List[str] = []

    lines.append("🔮 **ПОЛНЫЙ НУМЕРОЛОГИЧЕСКИЙ РАСЧЁТ**")
    lines.append(f"📅 Дата рождения: {day:02d}.{month:02d}.{year}")
    if full_name_translit:
        lines.append(f"👤 Имя: {full_name_translit}")
    lines.append("")

    # Жизненный путь
    lp = data["life_path"]
    lines.append(f"🛤 **Число Жизненного Пути: {lp['number']}**")
    lines.append(f"   _{lp['calculation']}_")
    lines.append("")

    # Число дня рождения
    bn = data["birthday_number"]
    lines.append(f"🎁 **Число Дня Рождения: {bn['number']}**")
    if bn.get("is_master_number"):
        lines.append("   ✨ _Мастер-число_")
    lines.append(f"   {bn['meaning']}")
    lines.append("")

    if full_name_translit:
        # Число Судьбы
        dn = data["destiny"]
        lines.append(f"⭐ **Число Судьбы: {dn['number']}**")
        lines.append(f"   _{dn['calculation']}_")
        lines.append("")

        # Число Души
        su = data["soul_urge"]
        lines.append(f"💖 **Число Души: {su['number']}**")
        lines.append(f"   _{su['calculation']}_")
        lines.append("")

        # Число Личности
        pn = data["personality"]
        lines.append(f"🎭 **Число Личности: {pn['number']}**")
        lines.append(f"   _{pn['calculation']}_")
        lines.append("")

    # Число отношения
    an = data["attitude_number"]
    lines.append(f"👀 **Число Отношения: {an['number']}**")
    lines.append(f"   {an['meaning']}")
    lines.append("")

    # Рациональное мышление
    rt = data["rational_thought"]
    lines.append(f"🧠 **Число Рационального Мышления: {rt['number']}**")
    lines.append(f"   {rt['meaning']}")
    lines.append("")

    if full_name_translit:
        # Число зрелости
        mn = data["maturity_number"]
        lines.append(f"🌱 **Число Зрелости: {mn['number']}**")
        lines.append(f"   {mn['meaning']}")
        lines.append("")

        # Число баланса
        bl = data["balance_number"]
        lines.append(f"⚖ **Число Баланса: {bl['number']}**")
        lines.append(f"   {bl['meaning']}")
        lines.append("")

        # Подсознательное «Я»
        sc = data["subconscious_self"]
        lines.append(f"🌀 **Подсознательное «Я»: {sc['number']}**")
        lines.append(f"   Уникальных чисел: {sc['distinct_numbers']}")
        lines.append(f"   {sc['meaning']}")
        lines.append("")

        # Скрытая страсть
        hp = data["hidden_passion"]
        for passion in hp.get("hidden_passions", []):
            lines.append(
                f"🔥 **Скрытая Страсть: {passion['number']}** "
                f"(частота: {passion['frequency']})"
            )
            lines.append(f"   {passion['meaning']}")
        lines.append("")

        # Кармические уроки
        kl = data["karmic_lessons"]
        if kl["has_karmic_lessons"]:
            lines.append("📚 **Кармические Уроки:**")
            for lesson in kl["karmic_lessons"]:
                lines.append(f"   ❌ Урок {lesson['number']}: {lesson['meaning']}")
        else:
            lines.append("📚 **Кармические Уроки:** нет — все числа 1-9 присутствуют в имени.")
        lines.append("")

    # Кармические долги
    kd = data["karmic_debts"]
    if kd["has_karmic_debt"]:
        lines.append("⚠ **Кармические Долги:**")
        for debt_num, debt_desc in kd["descriptions"].items():
            lines.append(f"   🔸 Долг {debt_num}: {debt_desc}")
    else:
        lines.append("✅ **Кармические Долги:** не обнаружены.")
    lines.append("")

    # Вершины
    pin = data["pinnacle_numbers"]
    lines.append("🏔 **Вершины (Pinnacles):**")
    for p in pin["pinnacles"]:
        lines.append(f"   • Вершина {p['number']} ({p['age_range']} лет)")
        lines.append(f"     {p['meaning']}")
    lines.append("")

    # Вызовы
    ch = data["challenge_numbers"]
    lines.append("🧗 **Вызовы (Challenges):**")
    for c in ch["challenges"]:
        lines.append(f"   • {c['name']}: {c['number']}")
        lines.append(f"     {c['meaning']}")
    lines.append("")

    # Периодические циклы
    pc = data["period_cycles"]
    lines.append("🔄 **Периодические Циклы:**")
    for cycle in pc["period_cycles"]:
        lines.append(f"   • {cycle['name']} ({cycle['age_range']} лет): {cycle['number']}")
        lines.append(f"     {cycle['meaning']}")
    lines.append("")

    # Новые профессиональные расчёты
    if full_name_translit:
        # Транзитные буквы
        tl = data.get("transit_letters", {})
        if tl and tl.get("transits"):
            lines.append("✉️ **Транзитные Буквы:**")
            for t in tl["transits"]:
                lines.append(
                    f"   • {t['word_label']}: буква {t['current_letter']} "
                    f"(значение {t['current_value']}, осталось {t['years_remaining_in_transit']} лет)"
                )
                lines.append(f"     {t['meaning']}")
            lines.append("")

        # Число Сущности
        en = data.get("essence_number", {})
        if en and en.get("number"):
            lines.append(f"💎 **Число Сущности: {en['number']}**")
            transits_str = " + ".join(str(v) for v in en.get("transit_values", []))
            lines.append(f"   _Транзиты: {transits_str}_")
            lines.append(f"   {en['meaning']}")
            lines.append("")

        # Краеугольный и Завершающий Камни
        cc = data.get("cornerstone_capstone", {})
        if cc and cc.get("cornerstone", {}).get("letter"):
            cs = cc["cornerstone"]
            cp = cc["capstone"]
            lines.append(f"🧱 **Краеугольный Камень: {cs['letter']} (значение {cs['value']})**")
            lines.append(f"   {cs['meaning']}")
            lines.append("")
            lines.append(f"🏁 **Завершающий Камень: {cp['letter']} (значение {cp['value']})**")
            lines.append(f"   {cp['meaning']}")
            lines.append("")

        # Подсознательное «Я» (по имени, формула 9 - missing)
        ssn = data.get("subconscious_self_name", {})
        if ssn and ssn.get("number"):
            lines.append(f"🫧 **Подсознательное «Я» (по имени): {ssn['number']}**")
            lines.append(
                f"   Присутствуют: {ssn.get('present_numbers', [])} | "
                f"Отсутствуют: {ssn.get('missing_numbers', [])}"
            )
            lines.append(f"   {ssn['meaning']}")
            lines.append("")

        # Рациональное мышление (по имени)
        rtn = data.get("rational_thought_name", {})
        if rtn and rtn.get("number"):
            lines.append(f"🧩 **Рациональное Мышление (по имени): {rtn['number']}**")
            lines.append(
                f"   _Гласные «{rtn.get('first_word', '')}» = {rtn.get('vowel_sum', 0)} "
                f"+ первая буква = {rtn.get('first_letter_value', 0)}_"
            )
            lines.append(f"   {rtn['meaning']}")
            lines.append("")

    return "\n".join(lines)


def format_numerology_report_parts(day: int, month: int, year: int,
                                   full_name_translit: str = "",
                                   max_part_len: int = 4000) -> List[str]:
    """
    Разбивает полный отчёт на части для Telegram
    (лимит ~4096 символов на сообщение).
    """
    full_text = format_numerology_report(day, month, year, full_name_translit)

    if len(full_text) <= max_part_len:
        return [full_text]

    parts: List[str] = []
    paragraphs = full_text.split("\n\n")
    current_part = ""

    for para in paragraphs:
        if len(current_part) + len(para) + 2 > max_part_len:
            if current_part:
                parts.append(current_part.strip())
            current_part = para + "\n\n"
        else:
            current_part += para + "\n\n"

    if current_part.strip():
        parts.append(current_part.strip())

    # Добавляем номера частей
    if len(parts) > 1:
        parts = [f"{p}\n\n📄 Часть {i+1}/{len(parts)}" for i, p in enumerate(parts)]

    return parts
