def _reduce(n: int, keep_master: bool = True) -> int:
    """Reduce to single digit, optionally keeping master numbers 11, 22, 33."""
    if keep_master:
        while n > 9 and n not in (11, 22, 33):
            n = sum(int(d) for d in str(n))
    else:
        while n > 9:
            n = sum(int(d) for d in str(n))
    return n


def calculate_destiny_number(full_name_translit: str) -> Dict:
    """Calculate Destiny/Expression number from full name in transliteration.
    
    Uses Pythagorean numerology letter values.
    """
    PYTH_VALUES = {
        'a': 1, 'b': 2, 'c': 3, 'd': 4, 'e': 5, 'f': 6, 'g': 7, 'h': 8, 'i': 9,
        'j': 1, 'k': 2, 'l': 3, 'm': 4, 'n': 5, 'o': 6, 'p': 7, 'q': 8, 'r': 9,
        's': 1, 't': 2, 'u': 3, 'v': 4, 'w': 5, 'x': 6, 'y': 7, 'z': 8,
    }
    VOWELS = set('aeiou')
    
    name = full_name_translit.lower().replace(' ', '')
    total = sum(PYTH_VALUES.get(c, 0) for c in name)
    vowel_sum = sum(PYTH_VALUES.get(c, 0) for c in name if c in VOWELS)
    consonant_sum = total - vowel_sum
    
    return {
        "destiny_number": _reduce(total),
        "soul_number": _reduce(vowel_sum),       # Число Души (гласные)
        "personality_number": _reduce(consonant_sum),  # Число Личности (согласные)
        "total_sum": total,
    }


