def get_decanate(sign: str, day: int) -> str:
    """Get the specific decanate (third of sign) for a birth date."""
    sign = sign.lower().strip()
    decanates = DECANATES.get(sign, [])
    if not decanates:
        return ""
    # First 10 days = 1st decanate, next 10 = 2nd, last 10+ = 3rd
    if day <= 10:
        return decanates[0]
    elif day <= 20:
        return decanates[1]
    else:
        return decanates[2]


