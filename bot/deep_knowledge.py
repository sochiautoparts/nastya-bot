def calculate_balance_number(day: int, month: int, year: int) -> int:
    """Calculate Balance number from reduced digits of day, month, year."""
    d = _reduce(day, keep_master=False)
    m = _reduce(month, keep_master=False)
    y = _reduce(sum(int(dg) for dg in str(year)), keep_master=False)
    return _reduce(d + m + y, keep_master=False)


