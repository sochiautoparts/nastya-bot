# Джйотиш — система знаков (сидерический зодиак, смещение ~24° от тропического)
# Для определения Джанма-Раши (лунного знака) нужно знать точную позицию Луны
# Приблизительная конвертация: если тропический знак = X, то сидерический ≈ X - 1 знак (примерно)

def get_jyotish_rashi_approx(western_sign: str) -> str:
    """Approximate conversion from Western (tropical) to Vedic (sidereal) sign.

    In Jyotish the ayanamsha offset is about 24 degrees,
    so the sidereal sign is roughly one sign behind the tropical sign.
    This is APPROXIMATE — for exact calculation one needs an ephemeris.
    """
    sign_order = [
        "овен", "телец", "близнецы", "рак", "лев", "дева",
        "весы", "скорпион", "стрелец", "козерог", "водолей", "рыбы",
    ]
    rashi_order = [
        "Меша", "Вришабха", "Митхуна", "Карка", "Симха", "Канья",
        "Тула", "Вришчика", "Дхану", "Макара", "Кумбха", "Мина",
    ]

    western_sign = western_sign.lower().strip()
    if western_sign not in sign_order:
        return "Меша"  # default

    idx = sign_order.index(western_sign)
    # Sidereal is ~1 sign behind tropical
    sidereal_idx = (idx - 1) % 12
    return rashi_order[sidereal_idx]


