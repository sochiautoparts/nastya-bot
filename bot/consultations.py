_DATE_PATTERNS = [
    # DD.MM.YYYY
    re.compile(r'(\d{1,2})[./\-\s](\d{1,2})[./\-\s](\d{4})'),
    # YYYY.MM.DD
    re.compile(r'(\d{4})[./\-\s](\d{1,2})[./\-\s](\d{1,2})'),
    # DD MM YYYY (words)
    re.compile(r'(\d{1,2})\s+(\d{1,2})\s+(\d{4})'),
]


def parse_birth_date(text: str) -> Optional[Tuple[int, int, int]]:
    """Parse birth date from various formats.

    Returns (day, month, year) or None.
    """
    text = text.strip()

    for pattern in _DATE_PATTERNS:
        m = pattern.search(text)
        if m:
            g1, g2, g3 = int(m.group(1)), int(m.group(2)), int(m.group(3))

            # If first group is 4-digit year -> YYYY.MM.DD
            if g1 > 1900:
                return (g3, g2, g1)

            # Otherwise DD.MM.YYYY
            if 1 <= g1 <= 31 and 1 <= g2 <= 12 and g3 > 1900:
                return (g1, g2, g3)

    return None


