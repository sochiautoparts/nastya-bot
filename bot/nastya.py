def should_ask_stars(message_count: int, last_stars_ask: float) -> bool:
    """Decide if Nastya should ask for stars (not too often)."""
    # Ask every 5-8 messages on average
    if message_count < 3:
        return False
    # At least 2 minutes since last ask
    if time.time() - last_stars_ask < 120:
        return False
    # ~15% chance per message after 3 messages
    return random.random() < 0.15


