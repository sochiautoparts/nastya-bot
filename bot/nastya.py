def calculate_numerology(number_str: str) -> Dict:
    digits = [int(d) for d in number_str if d.isdigit()]
    if not digits:
        return {"number": 0, "meaning": "Хмм, тут цифр нет... Настя запуталась"}

    total = sum(digits)
    while total > 9 and total not in (11, 22, 33):
        total = sum(int(d) for d in str(total))

    meanings = {
        1: "Лидер! Ты как Настя — хочешь всё и сразу",
        2: "Дипломат. Но Настя не дипломат, Настя конфликтует",
        3: "Творческая натура! Как Настя",
        4: "Организованный. Скучно, но Настя уважает",
        5: "Свобода и приключения! Настя тоже хочет",
        6: "Семья и забота. Настя заботливая... иногда",
        7: "Мудрец. Как Настя когда философствует",
        8: "Деньги и власть! Настя одобряет",
        9: "Мечтатель. Настя тоже мечтает... о шопинге",
        11: "Мастер-число! Ты особенный, как Настя",
        22: "Мастер-строитель! Настя впечатлена",
        33: "Мастер-учитель! Это прям космос",
    }

    return {"number": total, "meaning": meanings.get(total, "Что-то загадочное...")}


def get_zodiac_info(sign: str) -> Optional[Dict]:
    sign = sign.lower().strip()
    if sign in ZODIAC_SIGNS:
        return {"sign": sign, "emoji": ZODIAC_SIGNS[sign]}
    return None
