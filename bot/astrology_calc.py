#  1. АСЦЕНДЕНТ (Восходящий знак) — приближённый расчёт
# ════════════════════════════════════════════════════════════════

def _calculate_obliquity(jd: float) -> float:
    """Рассчитать наклон эклиптики (облиkvность) на указанную дату.

    Использует формулу IAU 2006 для среднего наклона.
    Возвращает наклон в градусах.
    """
    T = (jd - 2451545.0) / 36525.0
    # Средний наклон эклиптики (IAU)
    obliquity = 23.4392911 - 0.0130042 * T - 1.64e-7 * T * T + 5.04e-7 * T * T * T
    return obliquity


def _calculate_gmst(jd: float) -> float:
    """Рассчитать Гринвичское среднее звёздное время (GMST) в градусах.

    Использует формулу Meeus, гл. 12.
    """
    T = (jd - 2451545.0) / 36525.0
    # GMST в секундах дуги
    gmst = (280.46061837
            + 360.98564736629 * (jd - 2451545.0)
            + 0.000387933 * T * T
            - T * T * T / 38710000.0)
    return _deg_norm(gmst)


def _calculate_ramc(jd: float, longitude: float) -> float:
    """Рассчитать Прямое восхождение Середины Неба (RAMC) в градусах.

    RAMC = GMST + долгота места
    """
    gmst = _calculate_gmst(jd)
    ramc = _deg_norm(gmst + longitude)
    return ramc


def calculate_ascendant_approx(birth_jd: float, latitude: float, longitude: float) -> Dict[str, Any]:
    """Приближённый расчёт Асцендента (Восходящего знака).

    Использует классическую формулу Асцендента через RAMC и наклон эклиптики.
    Точность: ±1-2° для средних широт.

    Параметры:
        birth_jd: Юлианский день рождения (UT)
        latitude: широта места рождения (градусы, +север)
        longitude: долгота места рождения (градусы, +восток)

    Возвращает:
        dict с ключами:
            sign: название знака Зодиака
            degree: долгота Асцендента в градусах
            degree_in_sign: градусы внутри знака
            formatted: форматированная строка 'XX° YY′ Знак'
            element: стихия
            cross: крест
            meaning: интерпретация
    """
    ramc = _calculate_ramc(birth_jd, longitude)
    obliquity = _calculate_obliquity(birth_jd)
    obliquity_rad = math.radians(obliquity)
    latitude_rad = math.radians(latitude)
    ramc_rad = math.radians(ramc)

    # Формула Асцендента:
    # tan(ASC) = cos(RAMC) / [-(sin(obliquity) * tan(latitude) + cos(obliquity) * sin(RAMC))]
    numerator = math.cos(ramc_rad)
    denominator = -(math.sin(obliquity_rad) * math.tan(latitude_rad)
                    + math.cos(obliquity_rad) * math.sin(ramc_rad))

    asc_lon = math.degrees(math.atan2(numerator, denominator))
    asc_lon = _deg_norm(asc_lon)

    sign, deg_in_sign, minutes = longitude_to_sign_degree(asc_lon)
    element = ZODIAC_ELEMENTS.get(sign, '')
    cross = ZODIAC_CROSSES.get(sign, '')
    meaning = ASCENDANT_MEANINGS.get(sign, '')

    return {
        'sign': sign,
        'degree': round(asc_lon, 4),
        'degree_in_sign': deg_in_sign,
        'minutes_in_sign': int(minutes),
        'formatted': format_longitude(asc_lon),
        'element': element,
        'cross': cross,
        'meaning': meaning,
    }


