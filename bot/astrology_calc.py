# Определение аспектов: (название, угол, допустимая орба по умолчанию)
ASPECT_TYPES: List[Tuple[str, float, float]] = [
    ('Соединение',   0.0,   10.0),
    ('Полусекстиль', 30.0,   2.0),
    ('Секстиль',     60.0,   6.0),
    ('Квадратура',   90.0,   7.0),
    ('Трин',        120.0,   8.0),
    ('Квинкункс',   150.0,   3.0),
    ('Оппозиция',   180.0,  10.0),
]


def calculate_aspects(
    positions1: Dict[str, float],
    positions2: Optional[Dict[str, float]] = None,
    orb: float = 8.0,
) -> List[Dict[str, Any]]:
    """Рассчитать аспекты между планетами.

    Если positions2 не указано — рассчитываются аспекты между планетами одного набора
    (внутренние аспекты). Если указано — аспекты между двумя наборами (синастрия).

    Параметры:
        positions1: словарь {имя_планеты: долгота}
        positions2: второй набор (опционально, для синастрии)
        orb: максимальная орба в градусах (по умолчанию 8°)

    Возвращает:
        список словарей с аспектами:
        [
            {
                'planet1': 'sun',
                'planet2': 'moon',
                'aspect': 'Оппозиция',
                'exact_angle': 180.0,
                'actual_angle': 178.5,
                'orb': 1.5,
                'applying': True/False,
                'meaning': '...',
            },
            ...
        ]
    """
    aspects = []

    if positions2 is None:
        # Внутренние аспекты — перебираем все пары
        planet_list = list(positions1.items())
        for i in range(len(planet_list)):
            for j in range(i + 1, len(planet_list)):
                name1, lon1 = planet_list[i]
                name2, lon2 = planet_list[j]
                aspect_info = _check_aspect(name1, lon1, name2, lon2, orb)
                if aspect_info:
                    aspects.append(aspect_info)
    else:
        # Синастрия — аспекты между двумя наборами
        for name1, lon1 in positions1.items():
            for name2, lon2 in positions2.items():
                if name1 == name2:
                    continue  # Пропускаем одну и ту же планету
                aspect_info = _check_aspect(name1, lon1, name2, lon2, orb)
                if aspect_info:
                    aspects.append(aspect_info)

    return aspects


def _check_aspect(
    name1: str, lon1: float,
    name2: str, lon2: float,
    max_orb: float,
) -> Optional[Dict[str, Any]]:
    """Проверить, есть ли аспект между двумя планетами.

    Возвращает dict с информацией об аспекте или None.
    """
    # Угловое расстояние
    diff = abs(lon1 - lon2)
    if diff > 180.0:
        diff = 360.0 - diff

    best_aspect = None
    best_orb_value = max_orb + 1.0  # Больше любого допустимого орба

    for aspect_name, aspect_angle, default_orb in ASPECT_TYPES:
        # Используем минимальный из запрошенного орба и орба для данного аспекта
        effective_orb = min(max_orb, default_orb)
        orb_value = abs(diff - aspect_angle)

        if orb_value <= effective_orb and orb_value < best_orb_value:
            best_aspect = aspect_name
            best_orb_value = orb_value
            best_angle = aspect_angle

    if best_aspect is None:
        return None

    # Определяем applying/separating
    # Applying: более быстрая планета приближается к аспекту
    # Для упрощения используем разницу скоростей планет
    applying = _is_applying(name1, lon1, name2, lon2, best_angle)

    meaning = ASPECT_MEANINGS.get(best_aspect, '')

    return {
        'planet1': name1,
        'planet1_name': PLANET_NAMES_RU.get(name1, name1),
        'planet2': name2,
        'planet2_name': PLANET_NAMES_RU.get(name2, name2),
        'aspect': best_aspect,
        'exact_angle': best_angle,
        'actual_angle': round(diff, 2),
        'orb': round(best_orb_value, 2),
        'applying': applying,
        'status': 'сходящийся' if applying else 'расходящийся',
        'meaning': meaning,
    }


# Средние суточные скорости планет (градусы/день) для определения applying/separating
_PLANET_SPEEDS: Dict[str, float] = {
    'moon':        13.18,
    'mercury':      1.38,
    'venus':        1.20,
    'sun':          0.986,
    'mars':         0.524,
    'jupiter':      0.083,
    'saturn':       0.034,
    'uranus':       0.012,
    'neptune':      0.006,
    'pluto':        0.004,
    'north_node':  -0.053,  # Ретроградное движение
    'south_node':   0.053,  # Прямое (симметрично)
    'chiron':       0.004,
}


def _is_applying(name1: str, lon1: float, name2: str, lon2: float, aspect_angle: float) -> bool:
    """Определить, является ли аспект сходящимся (applying).

    Аспект сходящийся, если более быстрая планета приближается к точному аспекту.
    """
    speed1 = abs(_PLANET_SPEEDS.get(name1, 0.0))
    speed2 = abs(_PLANET_SPEEDS.get(name2, 0.0))

    if speed1 == 0 and speed2 == 0:
        return False

    # Определяем, какая планета быстрее
    if speed1 >= speed2:
        faster_name, faster_lon = name1, lon1
        slower_lon = lon2
    else:
        faster_name, faster_lon = name2, lon2
        slower_lon = lon1

    # Целевая позиция для сходящегося аспекта
    target_lon = _deg_norm(slower_lon + aspect_angle)
    target_lon_minus = _deg_norm(slower_lon - aspect_angle)

    # Расстояние от быстрой планеты до целевой позиции (по кратчайшей)
    dist_plus = (target_lon - faster_lon + 180.0) % 360.0 - 180.0
    dist_minus = (target_lon_minus - faster_lon + 180.0) % 360.0 - 180.0

    # Выбираем ближайшую цель
    if abs(dist_plus) <= abs(dist_minus):
        dist = dist_plus
    else:
        dist = dist_minus

    # Если расстояние уменьшается (быстрая планета догоняет), аспект сходящийся
    # Быстрая планета движется вперёд (по зодиаку), поэтому если цель впереди — applying
    return dist > 0


