def calculate_all_astrology(
    day: int,
    month: int,
    year: int,
    birth_time_str: str,
    birth_place: str,
) -> Dict[str, Any]:
    """Мастер-функция: полный астрологический расчёт.

    Вызывает все расчётные функции и возвращает комплексный результат.

    Параметры:
        day: день рождения (1-31)
        month: месяц рождения (1-12)
        year: год рождения
        birth_time_str: время рождения в формате 'HH:MM' или 'HH:MM Город'
        birth_place: место рождения (название города)

    Возвращает:
        словарь со всеми астрологическими данными
    """
    # ─── Парсинг входных данных ───
    hour, minute = _parse_birth_time(birth_time_str)
    tz_offset = _get_timezone_offset(birth_place)
    latitude, longitude = _get_city_coordinates(birth_place)

    # ─── Юлианский день ───
    # Создаём datetime в UTC
    ut_hour = hour - tz_offset
    try:
        birth_dt = datetime(year, month, day, int(ut_hour), int((ut_hour % 1) * 60),
                            tzinfo=timezone.utc)
    except (ValueError, OverflowError):
        # Некорректная дата/время — корректируем
        birth_dt = datetime(year, month, day, 12, 0, tzinfo=timezone.utc)

    birth_jd = _datetime_to_jd(birth_dt)

    # ─── Планетные позиции ───
    planet_positions = calc_all_planets(birth_jd)

    # ─── Асцендент ───
    ascendant = calculate_ascendant_approx(birth_jd, latitude, longitude)

    # ─── MC ───
    midheaven = calculate_midheaven_approx(birth_jd, latitude, longitude)

    # ─── Дома ───
    house_cusps = calculate_house_cusps_approx(ascendant['degree'], midheaven['degree'])

    # ─── Аспекты ───
    aspects = calculate_aspects(planet_positions, orb=8.0)

    # ─── Фаза Луны ───
    moon_phase = calculate_moon_phase(birth_jd)

    # ─── Часть Фортуны ───
    # Определяем ночное ли рождение (Солнце ниже горизонта)
    sun_lon = planet_positions.get('sun', 0.0)
    is_night = _is_night_birth(birth_jd, sun_lon, latitude, longitude)
    part_of_fortune = calculate_part_of_fortune(
        sun_lon,
        planet_positions.get('moon', 0.0),
        ascendant['degree'],
        is_night,
    )

    # ─── Арабские Части ───
    arabic_parts = calculate_arabic_parts(
        ascendant['degree'],
        midheaven['degree'],
        sun_lon,
        planet_positions.get('moon', 0.0),
        planet_positions.get('venus', 0.0),
        is_night,
    )

    # ─── Управитель Гороскопа ───
    chart_ruler = determine_chart_ruler(ascendant.get('sign', 'Овен'))

    # ─── Ретроградность (улучшенная) ───
    retrogrades = detect_retrogrades(birth_jd)

    # ─── Планеты в домах ───
    planets_in_houses = calculate_planets_in_houses(planet_positions, house_cusps)

    # ─── Солярный возврат ───
    current_year = datetime.now().year
    solar_return = calculate_solar_return(birth_jd, current_year)

    # ─── Сводная информация о Солнце ───
    sun_sign, sun_deg, sun_min = longitude_to_sign_degree(sun_lon)

    # ─── Сводная информация о Луне ───
    moon_lon = planet_positions.get('moon', 0.0)
    moon_sign, moon_deg, moon_min = longitude_to_sign_degree(moon_lon)

    # ─── Формируем итоговый словарь ───
    result = {
        # Входные данные
        'input': {
            'day': day,
            'month': month,
            'year': year,
            'birth_time': f'{hour:02d}:{minute:02d}',
            'birth_place': birth_place,
            'timezone_offset': tz_offset,
            'latitude': latitude,
            'longitude': longitude,
            'julian_day': round(birth_jd, 6),
        },

        # Позиции планет
        'planets': {},
        'sun_sign': {
            'sign': sun_sign,
            'degree': sun_deg,
            'minutes': int(sun_min),
            'formatted': format_longitude(sun_lon),
            'element': ZODIAC_ELEMENTS.get(sun_sign, ''),
            'cross': ZODIAC_CROSSES.get(sun_sign, ''),
        },
        'moon_sign': {
            'sign': moon_sign,
            'degree': moon_deg,
            'minutes': int(moon_min),
            'formatted': format_longitude(moon_lon),
            'element': ZODIAC_ELEMENTS.get(moon_sign, ''),
        },

        # Асцендент
        'ascendant': ascendant,

        # MC
        'midheaven': midheaven,

        # Дома
        'houses': house_cusps,

        # Аспекты
        'aspects': aspects,
        'aspects_count': len(aspects),

        # Фаза Луны
        'moon_phase': moon_phase,

        # Часть Фортуны
        'part_of_fortune': part_of_fortune,

        # Арабские Части
        'arabic_parts': arabic_parts,

        # Управитель Гороскопа
        'chart_ruler': chart_ruler,

        # Ретроградность
        'retrogrades': {
            name: info for name, info in retrogrades.items() if info['retrograde']
        },
        'retrograde_planets_list': [
            info['name_ru'] for name, info in retrogrades.items()
            if info['retrograde'] and name != 'north_node'
        ],

        # Планеты в домах
        'planets_in_houses': planets_in_houses,

        # Солярный возврат
        'solar_return': solar_return,

        # Ночное ли рождение
        'is_night_birth': is_night,
    }

    # Форматируем позиции планет
    for planet_name, lon in planet_positions.items():
        sign, deg, minutes = longitude_to_sign_degree(lon)
        retro_info = retrogrades.get(planet_name, {})
        result['planets'][planet_name] = {
            'longitude': round(lon, 4),
            'sign': sign,
            'degree_in_sign': deg,
            'minutes_in_sign': int(minutes),
            'formatted': format_longitude(lon),
            'name_ru': PLANET_NAMES_RU.get(planet_name, planet_name),
            'retrograde': retro_info.get('retrograde', False),
            'retrograde_meaning': retro_info.get('meaning', ''),
        }

    return result


def _is_night_birth(birth_jd: float, sun_lon: float, latitude: float, longitude: float) -> bool:
    """Определить, было ли рождение ночью (Солнце ниже горизонта).

    Упрощённый алгоритм: сравниваем RAMC с долготой Солнца.
    Если Солнце в нижней кульминации (IC) — ночь.
    """
    ramc = _calculate_ramc(birth_jd, longitude)
    # MC = atan2(sin(RAMC), cos(obliquity)*cos(RAMC))
    obliquity = _calculate_obliquity(birth_jd)
    obliquity_rad = math.radians(obliquity)
    ramc_rad = math.radians(ramc)

    mc_lon = math.degrees(math.atan2(math.sin(ramc_rad),
                                      math.cos(obliquity_rad) * math.cos(ramc_rad)))
    mc_lon = _deg_norm(mc_lon)

    # IC = MC + 180°
    ic_lon = _deg_norm(mc_lon + 180.0)

    # Расстояние Солнца от IC
    dist_to_ic = abs((sun_lon - ic_lon + 180.0) % 360.0 - 180.0)
    # Расстояние Солнца от MC
    dist_to_mc = abs((sun_lon - mc_lon + 180.0) % 360.0 - 180.0)

    # Если Солнце ближе к IC чем к MC — ночь
    return dist_to_ic < dist_to_mc


