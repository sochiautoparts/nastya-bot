def calculate_planets_in_houses(
    planet_positions: Dict[str, float],
    house_cusps: List[Dict[str, Any]],
) -> Dict[str, Dict[str, Any]]:
    """Распределить планеты по домам.

    Планета находится в том доме, чей куспид предшествует её долготе,
    а следующий куспид — после неё.

    Параметры:
        planet_positions: словарь {имя_планеты: долгота}
        house_cusps: список куспидов от calculate_house_cusps_approx

    Возвращает:
        dict {имя_планеты: {'house': номер, 'house_name': ..., 'description': ..., ...}}
    """
    # Извлекаем долготы куспидов
    cusp_degrees = [hc['cusp_degree'] for hc in house_cusps]

    result = {}
    for planet_name, planet_lon in planet_positions.items():
        house_num = _find_house(planet_lon, cusp_degrees)
        house_info = None
        for hc in house_cusps:
            if hc['house'] == house_num:
                house_info = hc
                break

        name_ru = PLANET_NAMES_RU.get(planet_name, planet_name)

        result[planet_name] = {
            'house': house_num,
            'house_name': house_info['name'] if house_info else f'{house_num} дом',
            'house_description': house_info['description'] if house_info else '',
            'planet_name_ru': name_ru,
            'planet_longitude': round(planet_lon, 4),
            'formatted': f'{name_ru} в {house_info["name"] if house_info else house_num} доме' ,
        }

    return result


def _find_house(lon: float, cusp_degrees: List[float]) -> int:
    """Найти номер дома, в котором находится точка с заданной долготой.

    Параметры:
        lon: долгота точки
        cusp_degrees: список долгот куспидов (12 элементов)

    Возвращает:
        номер дома (1-12)
    """
    lon = lon % 360.0
    for i in range(12):
        cusp_start = cusp_degrees[i] % 360.0
        cusp_end = cusp_degrees[(i + 1) % 12] % 360.0

        if cusp_start < cusp_end:
            # Нормальный случай: куспид не пересекает 0°
            if cusp_start <= lon < cusp_end:
                return i + 1
        else:
            # Куспид пересекает 0° Овна
            if lon >= cusp_start or lon < cusp_end:
                return i + 1

    # Fallback — ближайший куспид
    min_dist = 999.0
    best_house = 1
    for i in range(12):
        dist = min(abs(lon - cusp_degrees[i]), 360.0 - abs(lon - cusp_degrees[i]))
        if dist < min_dist:
            min_dist = dist
            best_house = i + 1
    return best_house


