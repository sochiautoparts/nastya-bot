#  2. MC (Середина Неба / Midheaven) — приближённый расчёт
# ════════════════════════════════════════════════════════════════

def calculate_midheaven_approx(birth_jd: float, latitude: float, longitude: float) -> Dict[str, Any]:
    """Приближённый расчёт MC (Середины Неба).

    MC — точка пересечения эклиптики с небесным меридианом.
    Использует формулу: tan(MC) = tan(RAMC) / cos(obliquity)

    Параметры:
        birth_jd: Юлианский день рождения (UT)
        latitude: широта места рождения (не используется для MC, но оставлена для совместимости)
        longitude: долгота места рождения (градусы, +восток)

    Возвращает:
        dict с ключами: sign, degree, degree_in_sign, formatted, meaning
    """
    ramc = _calculate_ramc(birth_jd, longitude)
    obliquity = _calculate_obliquity(birth_jd)
    obliquity_rad = math.radians(obliquity)
    ramc_rad = math.radians(ramc)

    # Формула MC:
    # tan(MC) = tan(RAMC) / cos(obliquity)
    mc_lon = math.degrees(math.atan2(math.sin(ramc_rad),
                                      math.cos(obliquity_rad) * math.cos(ramc_rad)))
    mc_lon = _deg_norm(mc_lon)

    sign, deg_in_sign, minutes = longitude_to_sign_degree(mc_lon)
    meaning = ASCENDANT_MEANINGS.get(sign, '')  # MC интерпретируется по знаку

    return {
        'sign': sign,
        'degree': round(mc_lon, 4),
        'degree_in_sign': deg_in_sign,
        'minutes_in_sign': int(minutes),
        'formatted': format_longitude(mc_lon),
        'meaning': f'MC в знаке {sign} — направление карьеры и социального предназначения. {meaning}',
    }


