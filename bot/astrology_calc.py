#  9. СОЛЯРНЫЙ ВОЗВРАТ (Solar Return)
# ════════════════════════════════════════════════════════════════

def calculate_solar_return(birth_jd: float, current_year: int) -> Dict[str, Any]:
    """Рассчитать Юлианский день Солярного Возврата для указанного года.

    Солярный возврат — момент, когда транзитное Солнце возвращается в точку
    натального Солнца (ту же эклиптическую долготу).

    Параметры:
        birth_jd: Юлианский день рождения
        current_year: год, для которого рассчитывается Солярный возврат

    Возвращает:
        dict с ключами: solar_return_jd, date, sun_longitude, note
    """
    # Долгота натального Солнца
    birth_sun = _sun_longitude(birth_jd)
    target_lon = birth_sun

    # Приближённая дата: день рождения в текущем году
    # Используем hd_calc _datetime_to_jd для конвертации
    # Сначала оцениваем приблизительный JD дня рождения в текущем году
    birth_dt = _jd_to_datetime_approx(birth_jd)
    month = birth_dt[1]
    day = birth_dt[2]

    try:
        approx_dt = datetime(current_year, month, day, 12, 0, 0, tzinfo=timezone.utc)
    except ValueError:
        # 29 февраля в невысокосный год
        approx_dt = datetime(current_year, 3, 1, 12, 0, 0, tzinfo=timezone.utc)

    approx_jd = _datetime_to_jd(approx_dt)

    # Итеративное уточнение (Ньютон-Рафсон)
    sr_jd = approx_jd
    for _ in range(50):
        sr_sun = _sun_longitude(sr_jd)
        diff = (sr_sun - target_lon + 180.0) % 360.0 - 180.0
        if abs(diff) < 0.0001:
            break
        # Солнце движется ~0.9856°/день
        sr_jd -= diff / 0.9856

    # Конвертируем JD обратно в дату
    sr_date = _jd_to_datetime_approx(sr_jd)

    return {
        'solar_return_jd': round(sr_jd, 6),
        'year': current_year,
        'date': f'{sr_date[0]:04d}-{sr_date[1]:02d}-{sr_date[2]:02d}',
        'time_approx': f'{sr_date[3]:02d}:{sr_date[4]:02d}',
        'natal_sun_longitude': round(target_lon, 4),
        'solar_return_sun_longitude': round(_sun_longitude(sr_jd), 4),
        'note': f'Солярный возврат {current_year} года — момент обновления жизненного цикла.',
    }


def _jd_to_datetime_approx(jd: float) -> Tuple[int, int, int, int, int]:
    """Приближённое преобразование Юлианского дня в (год, месяц, день, час, минуту).

    Упрощённый обратный алгоритм Мёйса.
    """
    jd = jd + 0.5
    Z = int(jd)
    F = jd - Z

    if Z < 2299161:
        A = Z
    else:
        alpha = int((Z - 1867216.25) / 36524.25)
        A = Z + 1 + alpha - int(alpha / 4)

    B = A + 1524
    C = int((B - 122.1) / 365.25)
    D = int(365.25 * C)
    E = int((B - D) / 30.6001)

    day_decimal = B - D - int(30.6001 * E) + F
    day = int(day_decimal)
    hour_decimal = (day_decimal - day) * 24.0
    hour = int(hour_decimal)
    minute = int((hour_decimal - hour) * 60.0)

    if E < 14:
        month = E - 1
    else:
        month = E - 13

    if month > 2:
        year = C - 4716
    else:
        year = C - 4715

    return year, month, day, hour, minute


