def calculate_moon_phase(birth_jd: float) -> Dict[str, Any]:
    """Рассчитать фазу Луны на момент рождения.

    Использует разницу долгот Солнца и Луны для определения фазы.

    Параметры:
        birth_jd: Юлианский день рождения (UT)

    Возвращает:
        dict с ключами:
            phase_name: название фазы на русском
            illumination: процент освещённости Луны (0-100)
            phase_angle: угол фазы в градусах
            elongation: элонгация Луна-Солнце в градусах
            meaning: интерпретация
    """
    sun_lon = _sun_longitude(birth_jd)
    moon_lon = _moon_longitude(birth_jd)

    # Элонгация: угловое расстояние Луны от Солнца
    elongation = (moon_lon - sun_lon) % 360.0

    # Фазовый угол
    phase_angle = elongation

    # Процент освещённости
    illumination = (1.0 - math.cos(math.radians(elongation))) / 2.0 * 100.0

    # Определение названия фазы по элонгации
    if elongation < 22.5 or elongation >= 337.5:
        phase_name = 'Новолуние'
    elif 22.5 <= elongation < 67.5:
        phase_name = 'Растущий серп'
    elif 67.5 <= elongation < 112.5:
        phase_name = 'Первая четверть'
    elif 112.5 <= elongation < 157.5:
        phase_name = 'Растущая Луна'
    elif 157.5 <= elongation < 202.5:
        phase_name = 'Полнолуние'
    elif 202.5 <= elongation < 247.5:
        phase_name = 'Убывающая Луна'
    elif 247.5 <= elongation < 292.5:
        phase_name = 'Последняя четверть'
    else:
        phase_name = 'Убывающий серп'

    meaning = MOON_PHASE_MEANINGS.get(phase_name, '')

    return {
        'phase_name': phase_name,
        'illumination': round(illumination, 1),
        'phase_angle': round(phase_angle, 2),
        'elongation': round(elongation, 2),
        'meaning': meaning,
    }


