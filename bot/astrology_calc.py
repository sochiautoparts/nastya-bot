def longitude_to_sign_degree(lon: float) -> Tuple[str, int, float]:
    """Перевести эклиптическую долготу в знак, градусы и минуты внутри знака.

    Возвращает: (название_знака, градусы_в_знаке, минуты_в_знаке)
    """
    lon = lon % 360.0
    sign_index = int(lon / 30.0)
    if sign_index >= 12:
        sign_index = 11
    sign = ZODIAC_SIGNS[sign_index]
    degrees_in_sign = lon - sign_index * 30.0
    deg_int = int(degrees_in_sign)
    minutes = (degrees_in_sign - deg_int) * 60.0
    return sign, deg_int, minutes


def format_longitude(lon: float) -> str:
    """Форматировать долготу как 'XX° YY′ Знак ♯'."""
    sign, deg, minutes = longitude_to_sign_degree(lon)
    symbol = ZODIAC_SYMBOLS.get(sign, '')
    return f"{deg}° {int(minutes):02d}′ {sign} {symbol}"


