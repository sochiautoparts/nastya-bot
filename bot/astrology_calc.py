def format_astrology_report(data: Dict[str, Any]) -> str:
    """Сформировать текстовый астрологический отчёт на русском языке.

    Параметры:
        data: результат calculate_all_astrology()

    Возвращает:
        форматированную строку с полным отчётом
    """
    lines = []

    # Заголовок
    inp = data.get('input', {})
    lines.append('🌟 АСТРОЛОГИЧЕСКИЙ РАСЧЁТ 🌟')
    lines.append(f'📅 Дата: {inp.get("day", "?")}.{inp.get("month", "?"):02d}.{inp.get("year", "?")}')
    lines.append(f'🕐 Время: {inp.get("birth_time", "?")} (UTC{inp.get("timezone_offset", 0):+.0f})')
    lines.append(f'📍 Место: {inp.get("birth_place", "?")} ({inp.get("latitude", 0):.2f}°, {inp.get("longitude", 0):.2f}°)')
    lines.append('')

    # Солнце и Луна
    sun = data.get('sun_sign', {})
    moon = data.get('moon_sign', {})
    lines.append(f'☀️ Солнце: {sun.get("formatted", "?")} ({sun.get("element", "")}, {sun.get("cross", "")})')
    lines.append(f'🌙 Луна: {moon.get("formatted", "?")} ({moon.get("element", "")})')
    lines.append('')

    # Асцендент
    asc = data.get('ascendant', {})
    lines.append(f'⬆️ Асцендент: {asc.get("formatted", "?")} ({asc.get("element", "")}, {asc.get("cross", "")})')
    if asc.get('meaning'):
        lines.append(f'   {asc["meaning"]}')
    lines.append('')

    # MC
    mc = data.get('midheaven', {})
    lines.append(f'⏫ MC: {mc.get("formatted", "?")}')
    lines.append('')

    # Фаза Луны
    mp = data.get('moon_phase', {})
    lines.append(f'🌓 Фаза Луны: {mp.get("phase_name", "?")} (освещённость {mp.get("illumination", 0)}%)')
    if mp.get('meaning'):
        lines.append(f'   {mp["meaning"]}')
    lines.append('')

    # Планеты
    lines.append('🪐 ПЛАНЕТЫ:')
    planets = data.get('planets', {})
    for pname, pinfo in planets.items():
        retro_mark = ' ℞' if pinfo.get('retrograde') else ''
        lines.append(f'   {pinfo.get("name_ru", pname)}: {pinfo.get("formatted", "?")}{retro_mark}')
    lines.append('')

    # Ретроградные планеты
    retro_list = data.get('retrograde_planets_list', [])
    if retro_list:
        lines.append(f'🔄 Ретроградные планеты: {", ".join(retro_list)}')
        retrogrades = data.get('retrogrades', {})
        for rname, rinfo in retrogrades.items():
            if rinfo.get('meaning'):
                lines.append(f'   {rinfo["meaning"]}')
        lines.append('')

    # Дома
    lines.append('🏠 ДОМА:')
    houses = data.get('houses', [])
    for h in houses:
        lines.append(f'   {h.get("name", "")}: {h.get("formatted", "?")}')
    lines.append('')

    # Планеты в домах
    lines.append('🗺️ ПЛАНЕТЫ В ДОМАХ:')
    pih = data.get('planets_in_houses', {})
    for pname, ph in sorted(pih.items(), key=lambda x: x[1].get('house', 0)):
        lines.append(f'   {ph.get("formatted", pname)}')
    lines.append('')

    # Аспекты
    aspects = data.get('aspects', [])
    if aspects:
        lines.append(f'🔗 АСПЕКТЫ ({len(aspects)}):')
        for a in aspects:
            status = 'сход.' if a.get('applying') else 'расх.'
            lines.append(
                f'   {a.get("planet1_name", "?")} — {a.get("planet2_name", "?")}: '
                f'{a.get("aspect", "?")} (орб {a.get("orb", 0):.1f}°, {status})'
            )
        lines.append('')

    # Часть Фортуны
    pof = data.get('part_of_fortune', {})
    lines.append(f'💎 Часть Фортуны: {pof.get("formatted", "?")} ({pof.get("formula_used", "")})')
    if pof.get('meaning'):
        lines.append(f'   {pof["meaning"]}')
    lines.append('')

    # Арабские Части
    ap = data.get('arabic_parts', {})
    if ap:
        lines.append('⚖️ АРАБСКИЕ ЧАСТИ:')
        for part_key, part_info in ap.items():
            lines.append(f'   {part_info.get("name", part_key)}: {part_info.get("formatted", "?")}')
            if part_info.get('meaning'):
                lines.append(f'     {part_info["meaning"]}')
        lines.append('')

    # Управитель Гороскопа
    cr = data.get('chart_ruler', {})
    if cr:
        lines.append(f'👑 Управитель Гороскопа: {cr.get("ruler_name_ru", "?")} (управитель {cr.get("ascendant_sign", "?")})')
        if cr.get('description'):
            lines.append(f'   {cr["description"]}')
        lines.append('')

    # Солярный возврат
    sr = data.get('solar_return', {})
    lines.append(f'☀️ Солярный возврат {sr.get("year", "?")}: {sr.get("date", "?")} ~{sr.get("time_approx", "?")} UTC')

    return '\n'.join(lines)
